import math

def manhattan_distance(p1: tuple[int, int], p2: tuple[int, int]) -> int:
    """
    Manhattan distance heuristic for 4-connected grid pathfinding:
        h(n) = |x_n - x_goal| + |y_n - y_goal|

    Theoretical Properties:
    - Admissible: Never overestimates the true minimal cost to the goal
      in a 4-connected grid with uniform step cost c=1 (h(n) <= h*(n)).
    - Consistent (Monotone): For any successor n' generated by action a,
      h(n) <= c(n, a, n') + h(n').
    """
    return abs(p1[0] - p2[0]) + abs(p1[1] - p2[1])

def euclidean_distance(p1: tuple[int, int], p2: tuple[int, int]) -> float:
    """
    Euclidean distance heuristic (straight line distance):
        h(n) = sqrt((x_n - x_goal)^2 + (y_n - y_goal)^2)
    Also admissible for 4-connected grid, but weaker (more conservative) than Manhattan.
    """
    return math.hypot(p1[0] - p2[0], p1[1] - p2[1])
